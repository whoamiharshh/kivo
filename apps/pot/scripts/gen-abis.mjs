// Regenerates lib/abis.ts from the Foundry build output so the app's ABIs
// can never drift from the deployed contracts.
//
//   cd ../../packages/contracts && forge build
//   npm run gen:abis
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = (name) =>
  resolve(here, "..", "..", "..", "packages", "contracts", "out", `${name}.sol`, `${name}.json`);

const abiOf = (name) => {
  try {
    return JSON.parse(readFileSync(out(name), "utf8")).abi;
  } catch {
    console.error(
      `Could not read artifact for ${name}. Run \`forge build\` in ../../packages/contracts first.`
    );
    process.exit(1);
  }
};

const file = `// AUTO-GENERATED by scripts/gen-abis.mjs — do not edit by hand.
// Regenerate: cd ../../packages/contracts && forge build && cd ../../apps/pot && pnpm gen:abis

export const potManagerAbi = ${JSON.stringify(abiOf("PotManager"), null, 2)} as const;

export const testRupeeAbi = ${JSON.stringify(abiOf("TestRupee"), null, 2)} as const;

export const socialPayAbi = ${JSON.stringify(abiOf("SocialPay"), null, 2)} as const;

export const giftAbi = ${JSON.stringify(abiOf("Gift"), null, 2)} as const;

export const behaviourSavingsAbi = ${JSON.stringify(abiOf("BehaviourSavings"), null, 2)} as const;

export const salaryStreamAbi = ${JSON.stringify(abiOf("SalaryStream"), null, 2)} as const;

export const incomeShareAbi = ${JSON.stringify(abiOf("IncomeShare"), null, 2)} as const;

export const microCoverAbi = ${JSON.stringify(abiOf("MicroCover"), null, 2)} as const;

export const accountabilityPoolAbi = ${JSON.stringify(abiOf("AccountabilityPool"), null, 2)} as const;
`;

writeFileSync(resolve(here, "..", "lib", "abis.ts"), file);
console.log("wrote lib/abis.ts");
